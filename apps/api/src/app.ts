import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import { config } from './config.js';
import { errorMiddleware } from './lib/errors.js';
import { storage } from './lib/storage.js';
import { identity } from './modules/identity.js';
import { users } from './modules/users.js';
import { business } from './modules/business.js';
import { media } from './modules/media.js';
import { content } from './modules/content.js';
import { marketplace } from './modules/marketplace.js';
import { feed } from './modules/feed.js';
import { messaging } from './modules/messaging.js';
import { search } from './modules/search.js';
import { admin } from './modules/admin.js';
import { transport } from './modules/transport.js';
import { offers } from './modules/offers.js';
import { bookings } from './modules/bookings.js';
import { videos } from './modules/videos.js';
import { circles } from './modules/circles.js';
import { clips } from './modules/clips.js';
import { stories } from './modules/stories.js';
import { payments, webhookHandler } from './modules/payments.js';
import { disputes } from './modules/disputes.js';
import { boosts } from './modules/boosts.js';
import { bundles } from './modules/bundles.js';
import { commerce } from './modules/commerce.js';
import { ops, readyRouter, writeLimiter } from './modules/ops.js';
import { requestLogger } from './lib/logger.js';
import { trust } from './modules/trust.js';
import { notifications } from './modules/notifications.js';
import { security } from './modules/security.js';
import { subscriptions } from './modules/subscriptions.js';
import { growth } from './modules/growth.js';
import compression from 'compression';
import { adminPayments } from './modules/adminPayments.js';

export function createApp() {
  const app = express();
  app.set('trust proxy', 1);
  app.disable('x-powered-by');
  app.use(requestLogger);
  app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
  app.use(compression());
  app.use(cors({ origin: config.WEB_ORIGIN.split(','), credentials: true }));
  // Stripe signs the raw body, so the webhook route must be registered before express.json()
  app.post('/api/webhooks/stripe', express.raw({ type: '*/*', limit: '1mb' }), webhookHandler);
  app.use(express.json({ limit: '200kb' }));
  app.use('/media', express.static(storage.root, { maxAge: '30d', immutable: true, index: false, dotfiles: 'deny' }));
  app.get('/health', (_req, res) => res.json({ ok: true }));
  app.use(readyRouter);
  app.use('/api', writeLimiter);
  app.use('/api', ops, identity, users, business, media, content, bundles, commerce, marketplace, feed, messaging, search, transport, offers, bookings, videos, circles, clips, stories, payments, disputes, boosts, adminPayments, growth, subscriptions, security, notifications, trust, admin);
  app.use('/api', (_req, res) => res.status(404).json({ error: { code: 'not_found', message: 'Not found' } }));
  app.use(errorMiddleware);
  return app;
}
